export function pointsForTries(max: number, tries: number): number {
  if (tries <= 1) return max;
  if (tries === 2) return Math.ceil(max / 2);
  return Math.max(1, Math.floor(max / 5));
}

export function starsFor(score: number, max: number): number {
  if (max <= 0) return 0;
  const p = score / max;
  if (p >= 0.9) return 3;
  if (p >= 0.7) return 2;
  return 1;
}

export function percentOf(score: number, max: number): number {
  if (max <= 0) return 0;
  return Math.round((score / max) * 100);
}

export function gradeLabel(percent: number): string {
  if (percent >= 90) return "ممتاز";
  if (percent >= 80) return "جيد جدًا";
  if (percent >= 70) return "جيد";
  if (percent >= 50) return "مقبول";
  return "يحتاج إلى متابعة";
}

