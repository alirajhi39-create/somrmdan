/* ---------- الأنواع ---------- */
export type BlankToken = { blank: string };
export type FillToken = string | BlankToken;

export type LearnBlock =
  | { kind: "text"; text: string }
  | { kind: "highlight"; title?: string; text: string }
  | { kind: "quran"; text: string; source: string }
  | { kind: "hadith"; text: string; source: string }
  | { kind: "list"; title?: string; items: string[] }
  | { kind: "light"; text: string }
  | { kind: "timeline" };

interface StationBase {
  key: string;
  icon: string;
  title: string;
  subtitle: string;
  maxPoints: number;
}

export interface LearnStation extends StationBase {
  type: "learn";
  blocks: LearnBlock[];
  tts: string;
}

export interface McqQuestion {
  prompt: string;
  options: string[];
  answer: number;
  explain: string;
}

export interface McqStation extends StationBase {
  type: "mcq";
  intro?: string;
  questions: McqQuestion[];
}

export interface OrderStation extends StationBase {
  type: "order";
  prompt: string;
  chunks: string[];
  font?: "amiri";
  source?: string;
  success: string;
}

export interface FillStation extends StationBase {
  type: "fill";
  prompt: string;
  lines: FillToken[][];
  bank: string[];
  font?: "amiri";
  success: string;
}

export interface TrueFalseStatement {
  text: string;
  answer: boolean;
  explain: string;
}

export interface TrueFalseStation extends StationBase {
  type: "truefalse";
  prompt: string;
  statements: TrueFalseStatement[];
}

export type Station = LearnStation | McqStation | OrderStation | FillStation | TrueFalseStation;

